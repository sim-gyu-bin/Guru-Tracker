          "bg-primary font-semibold text-primary-foreground hover:shadow-primary-glow motion-safe:hover:-translate-y-0.5",
        outline:
          "border-primary/60 bg-primary/5 text-foreground hover:border-primary hover:bg-primary hover:text-primary-foreground hover:shadow-primary-glow aria-expanded:border-primary aria-expanded:bg-primary aria-expanded:text-primary-foreground",
